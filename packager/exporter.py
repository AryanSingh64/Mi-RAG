async def chat_rag(request: Request):
    global SERVER_MEMORY
    content_type = request.headers.get("content-type", "")
    query_image_path = None
    query_image_url = None
    user_message = ""
    client_history = None
    top_k = 6

    if "application/json" in content_type:
        try:
            data = await request.json()
            user_message = str(data.get("message", "")).strip()
            top_k = int(data.get("top_k", 6))
            client_history = data.get("history", None)
        except Exception:
            pass
    else:
        form = await request.form()
        user_message = str(form.get("message", "")).strip()
        try:
            top_k = int(form.get("top_k", 6))
        except Exception:
            top_k = 6
        
        h_raw = form.get("history")
        if h_raw:
            try:
                import json
                client_history = json.loads(h_raw)
            except Exception:
                pass

        up_img = form.get("image")
        if up_img and hasattr(up_img, "filename") and up_img.filename:
            fname = f"query_{{uuid.uuid4().hex[:8]}}_{{up_img.filename}}"
            query_image_path = IMAGES_DIR / fname
            with open(query_image_path, "wb") as buffer:
                shutil.copyfileobj(up_img.file, buffer)
            query_image_url = f"/images/{{fname}}"

    effective_history = client_history if client_history is not None else SERVER_MEMORY

    if not user_message and not query_image_path:
        return ChatResponse(answer="Please enter a question or attach an image.", confidence_score=1.0, is_grounded=True, citations=[], images=[])

    # Check for greetings
    if user_message.lower() in ["hi", "hello", "hey", "greetings"]:
        reply = "Hello! I am your standalone, 100% private grounded enterprise RAG assistant. How can I assist you with your indexed documents today?"
        return ChatResponse(answer=reply, confidence_score=1.0, is_grounded=True, citations=[], images=[])

    query_vec = embedder.encode(user_message or "multimodal image analysis", convert_to_numpy=True).tolist()
    results = collection.query(query_embeddings=[query_vec], n_results=top_k, include=["documents", "metadatas", "distances"])

    raw_chunks = []
    if results["ids"] and len(results["ids"][0]) > 0:
        for i in range(len(results["ids"][0])):
            dist = results["distances"][0][i]
            sim = max(0.0, 1.0 - dist)
            if sim >= 0.18:
                raw_chunks.append({{
                    "text": results["documents"][0][i],
                    "metadata": results["metadatas"][0][i],
                    "source_file": results["metadatas"][0][i].get("source_file", "Document"),
                    "score": sim
                }})

    if not raw_chunks:
        return ChatResponse(
            answer="I could not find any relevant information about this in the pre-indexed documents.",
            confidence_score=0.0,
            is_grounded=False,
            citations=[],
            images=[],
            query_image_url=query_image_url
        )

    reranked_chunks = apply_attention_reranking(user_message, raw_chunks, effective_history)

    context_blocks = []
    unique_citations = {{}}
    for idx, c in enumerate(reranked_chunks[:5], start=1):
        context_blocks.append(f"--- DOCUMENT EXCERPT {{idx}} ({{c['source_file']}}) ---\\n{{c['text']}}")
        score_pct = round(c["score"] * 100, 1)
        if c["source_file"] not in unique_citations or score_pct > unique_citations[c["source_file"]]["relevance"]:
            unique_citations[c["source_file"]] = {{
                "source_file": c["source_file"],
                "relevance": score_pct,
                "text": c["text"][:200] + "..." if len(c["text"]) > 200 else c["text"]
            }}

    history_block = ""
    if effective_history:
        turns = []
        for h in effective_history[-4:]:
            r = "User" if h.get("role") == "user" else "Assistant"
            turns.append(f"{{r}}: {{h.get('content', '')}}")
        if turns:
            history_block = "RECENT CONVERSATION MEMORY (PRIOR TURNS):\\n" + "\\n".join(turns) + "\\n\\n"

    system_prompt = (
        "You are a 100% private, local offline document intelligence engine.\\n"
        "1. Deliver a direct, finished, and well-structured answer in clean Markdown.\\n"
        "2. Use conversation memory to resolve pronouns and follow-up references.\\n"
        "3. Answer ONLY using the factual context provided. Do not hallucinate."
    )

    joined_context = "\\n\\n".join(context_blocks)
    user_prompt = (
        f"KNOWLEDGE BASE CONTEXT:\\n"
        f"{{joined_context}}\\n\\n"
        f"{{history_block}}"
        f"USER QUERY: {{user_message}}\\n\\n"
        f"FINISHED GROUNDED ANSWER:"
    )

    payload = {{
        "model": MODEL_NAME,
        "messages": [{{"role": "system", "content": system_prompt}}, {{"role": "user", "content": user_prompt}}],
        "stream": False,
        "options": {{"temperature": 0.1, "num_ctx": 4096, "num_gpu": 99}}
    }}

    try:
        async with httpx.AsyncClient(timeout=90.0) as client:
            res = await client.post("http://localhost:11434/api/chat", json=payload)
            res.raise_for_status()
            ans_text = res.json().get("message", {{}}).get("content", "").strip()
    except Exception as e:
        ans_text = f"Local Ollama error: {{str(e)}}. Make sure Ollama is running (`ollama run {{MODEL_NAME}}`)."

    matched_images = extract_relevant_images(user_message, reranked_chunks, is_image_query=bool(query_image_path))

    SERVER_MEMORY.append({{"role": "user", "content": user_message or "[Visual Search]"}})
    SERVER_MEMORY.append({{"role": "assistant", "content": ans_text}})
    if len(SERVER_MEMORY) > 12:
        SERVER_MEMORY = SERVER_MEMORY[-12:]

    avg_conf = sum(c["score"] for c in reranked_chunks) / len(reranked_chunks)

    return ChatResponse(
        answer=ans_text,
        confidence_score=round(avg_conf, 4),
        is_grounded=True,
        citations=[Citation(**v) for v in unique_citations.values()],
        images=matched_images,
        query_image_url=query_image_url
    )

