    def create_package(self, session: RAGSession) -> Path:
        """
        Creates the complete standalone ZIP package from an active session.
        """
        bundle_dir = session.session_dir / "standalone_bundle"
        if bundle_dir.exists():
            shutil.rmtree(bundle_dir)
        bundle_dir.mkdir(parents=True, exist_ok=True)

        # 1. Copy the pre-indexed ChromaDB vector store
        dest_db = bundle_dir / "vector_db"
        shutil.copytree(session.db_dir, dest_db)

        # 2. Write Standalone Server & UI
        (bundle_dir / "server.py").write_text(
            self._generate_standalone_server_code(session.model_name, "all-MiniLM-L6-v2"),
            encoding="utf-8"
        )
        (bundle_dir / "index.html").write_text(
            self._generate_standalone_ui(session.model_name),
            encoding="utf-8"
        )

        # 3. Write requirements.txt
        requirements_txt = (
            "fastapi>=0.110.0\n"
            "uvicorn>=0.28.0\n"
            "pydantic>=2.6.0\n"
            "chromadb>=0.4.24\n"
            "sentence-transformers>=2.6.0\n"
            "httpx>=0.27.0\n"
        )
        (bundle_dir / "requirements.txt").write_text(requirements_txt, encoding="utf-8")

        # 4. Write run.bat (Windows Launcher)
        run_bat = (
            "@echo off\n"
            "echo Starting Production RAG Server...\n"
            "if not exist .venv (\n"
            "    echo Creating virtual environment...\n"
            "    python -m venv .venv\n"
            "    call .venv\\Scripts\\activate.bat\n"
            "    pip install -r requirements.txt\n"
            ") else (\n"
            "    call .venv\\Scripts\\activate.bat\n"
            ")\n"
            "python server.py\n"
            "pause\n"
        )
        (bundle_dir / "run.bat").write_text(run_bat, encoding="utf-8")

        # 5. Write run.sh (Linux/Mac Launcher)
        run_sh = (
            "#!/bin/bash\n"
            "echo 'Starting Production RAG Server...'\n"
            "if [ ! -d '.venv' ]; then\n"
            "    python3 -m venv .venv\n"
            "    source .venv/bin/activate\n"
            "    pip install -r requirements.txt\n"
            "else\n"
            "    source .venv/bin/activate\n"
            "fi\n"
            "python server.py\n"
        )
        (bundle_dir / "run.sh").write_text(run_sh, encoding="utf-8")

        # 6. Write Dockerfile
        dockerfile = (
            "FROM python:3.11-slim\n"
            "WORKDIR /app\n"
            "COPY requirements.txt .\n"
            "RUN pip install --no-cache-dir -r requirements.txt\n"
            "COPY . .\n"
            "EXPOSE 8000\n"
            "CMD [\"python\", \"server.py\"]\n"
        )
        (bundle_dir / "Dockerfile").write_text(dockerfile, encoding="utf-8")

        # 7. Write Installation & Setup Guide
        (bundle_dir / "INSTALL_GUIDE.md").write_text(
            self._generate_install_guide(session.model_name),
            encoding="utf-8"
        )

        # 8. Compress into ZIP
        zip_file_path = self.output_dir / f"rag_package_{session.session_id}.zip"
        with zipfile.ZipFile(zip_file_path, "w", zipfile.ZIP_DEFLATED) as zip_out:
            for root, _, files in os.walk(bundle_dir):
                for file in files:
                    full_p = Path(root) / file
                    arc_name = full_p.relative_to(bundle_dir)
                    zip_out.write(full_p, arcname=arc_name)

        return zip_file_path
