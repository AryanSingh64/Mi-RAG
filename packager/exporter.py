def apply_attention_reranking(query: str, raw_chunks: list, history: list) -> list:
    """Attention-weighted context reranking using query overlap and conversation focus."""
    query_words = set(re.findall(r"\\b\\w{{3,}}\\b", query.lower()))
    history_words = set()
    if history:
        for turn in history[-2:]:
            history_words.update(re.findall(r"\\b\\w{{3,}}\\b", str(turn.get("content", "")).lower()))

    scored = []
    for chunk in raw_chunks:
        text_lower = chunk["text"].lower()
        base_sim = chunk["score"]
        
        q_overlap = sum(1 for w in query_words if w in text_lower)
        q_boost = min(0.35, (q_overlap / max(1, len(query_words))) * 0.35)

        h_overlap = sum(1 for w in history_words if w in text_lower)
        h_boost = min(0.15, (h_overlap / max(1, len(history_words))) * 0.15) if history_words else 0.0

        diag_boost = 0.05 if "[DIAGRAM" in chunk["text"] else 0.0
        att_score = base_sim + q_boost + h_boost + diag_boost
        scored.append((att_score, chunk))

    scored.sort(key=lambda x: x[0], reverse=True)
    return [c for _, c in scored]

def extract_relevant_images(query: str, chunks: list, is_image_query: bool = False) -> list:
    visual_keywords = ["diagram", "figure", "chart", "plot", "graph", "architecture", "image", "photo", "show me", "table", "visual", "fig.", "fig "]
    explicit_visual = any(kw in query.lower() for kw in visual_keywords)

    if not is_image_query and not explicit_visual:
        has_high_diag = any("[DIAGRAM" in c["text"] and c["score"] >= 0.45 for c in chunks)
        if not has_high_diag:
            return []

    matched = []
    seen = set()
    for c in chunks:
        meta_url = c["metadata"].get("image_url", "").strip() if isinstance(c["metadata"], dict) else ""
        urls = [meta_url] if meta_url else []
        found = re.findall(r"\\[Image URL:\\s*(.*?)\\]", c["text"])
        urls.extend([u.strip() for u in found if u.strip()])

        for u in urls:
            if u and u not in seen:
                if "_page_" in u.lower() and not is_image_query and not explicit_visual:
                    continue
                seen.add(u)
                local_u = u.replace("/api/sessions/", "").split("/images/")[-1]
                served_url = f"/images/{{local_u}}" if (IMAGES_DIR / local_u).exists() else u
                p_num = c["metadata"].get("page_number", "") if isinstance(c["metadata"], dict) else ""
                caption = f"{{c['source_file']}}" + (f" (Page {{p_num}})" if p_num else "")
                matched.append(ImageMatch(
                    url=served_url,
                    filename=Path(u).name,
                    source_file=caption,
                    relevance=round(c["score"] * 100, 1)
                ))
                if len(matched) >= (3 if is_image_query else 2):
                    break
        if len(matched) >= (3 if is_image_query else 2):
            break
    return matched

